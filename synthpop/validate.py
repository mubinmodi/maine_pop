"""Validation report: synthetic estimates against published figures at every level.

    report = validate(stats, validation_stats, pub, blocks, holdout, diagnostics)
    report.write("docs/validation.md", "data/out/validation")
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

MOE_Z = 1.645


@dataclass
class Report:
    sections: list[tuple[str, str]] = field(default_factory=list)      # (title, markdown)
    tables: dict[str, pd.DataFrame] = field(default_factory=dict)       # name -> detail CSV
    headline: dict[str, str] = field(default_factory=dict)

    def write(self, md_path: str | Path, csv_dir: str | Path) -> None:
        csv_dir = Path(csv_dir)
        csv_dir.mkdir(parents=True, exist_ok=True)
        for name, df in self.tables.items():
            df.to_csv(csv_dir / f"{name}.csv", index=False)
        lines = ["# Validation report", "",
                 "Synthetic estimates for Portland, Maine, aggregated from parcels, compared with published Census figures. "
                 "Generated by `synthpop validate`; do not edit by hand.", "", "## Headline", ""]
        lines += [f"- **{k}**: {v}" for k, v in self.headline.items()]
        for title, body in self.sections:
            lines += ["", f"## {title}", "", body]
        Path(md_path).write_text("\n".join(lines) + "\n")


def _md(df: pd.DataFrame, floatfmt: str = "{:,.2f}") -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, (float, np.floating)) else (f"{v:,}" if isinstance(v, (int, np.integer)) else str(v)) for v in r]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def compare(stats: pd.DataFrame, pub: pd.DataFrame, level: str) -> pd.DataFrame:
    """Synthetic vs published for one level. RAE = |syn − pub| / MOE (UrbanPop's
    relative allocation error); RAE ≤ 1 means inside the published 90% MOE."""
    key = ["area_id", "variable", "category"]
    s = stats[(stats["level"] == level) & (stats["source"] == "synthetic")].set_index(key)
    p = pub[pub["level"] == level].set_index(key)
    j = p[["estimate", "se"]].join(s[["estimate", "se"]], lsuffix="_pub", rsuffix="_syn", how="inner")
    j = j.fillna(0).reset_index()
    moe = np.maximum(MOE_Z * j["se_pub"], 1.0)
    j["diff"] = j["estimate_syn"] - j["estimate_pub"]
    j["rae"] = j["diff"].abs() / moe
    j["level"] = level
    return j


def covered_tracts(pub: pd.DataFrame) -> set[str]:
    """Tracts whose published population equals the sum of their study-area block
    groups (within 1%): only those can be compared with synthetic totals."""
    pop = pub[(pub["variable"] == "population") & (pub["category"] == "total")]
    bg = pop[pop["level"] == "block_group"].assign(tract=lambda d: d["area_id"].str[:11]).groupby("tract")["estimate"].sum()
    tr = pop[pop["level"] == "tract"].set_index("area_id")["estimate"]
    both = tr.index.intersection(bg.index)
    return set(both[(bg[both] - tr[both]).abs() <= 0.01 * tr[both].clip(lower=1)])


def _fit_section(stats, pub, levels):
    rows, details = [], []
    tracts = covered_tracts(pub)
    for level in levels:
        c = compare(stats, pub, level)
        if level == "tract":
            c = c[c["area_id"].isin(tracts)]
        details.append(c)
        for var, g in c.groupby("variable"):
            rows.append({"level": level, "variable": var, "comparisons": len(g),
                         "within 90% MOE": f"{(g['rae'] <= 1).mean():.0%}",
                         "median RAE": float(g["rae"].median()),
                         "total synthetic": float(g["estimate_syn"].sum()), "total published": float(g["estimate_pub"].sum())})
    t = pd.DataFrame(rows)
    return t, pd.concat(details, ignore_index=True)


def _block_section(validation_stats, blocks, holdout):
    """Held-out blocks: does placement put the right share of each block group's
    people and homes in each block? Compared with 2020 Census block counts, which
    the validation run never saw, and with a land-area baseline."""
    b = blocks.set_index("area_id")
    syn = validation_stats[(validation_stats["level"] == "block") & (validation_stats["category"] == "total")]
    syn = syn.pivot_table(index="area_id", columns="variable", values="estimate", aggfunc="first")
    df = b[["block_group", "pop2020", "housing2020", "aland"]].join(syn, how="left").fillna(0)
    out = []
    for measure, census in (("population", "pop2020"), ("housing_units", "housing2020")):
        if measure not in df:
            continue
        bg_syn = df.groupby("block_group")[measure].transform("sum").replace(0, np.nan)
        bg_cen = df.groupby("block_group")[census].transform("sum").replace(0, np.nan)
        bg_area = df.groupby("block_group")["aland"].transform("sum").replace(0, np.nan)
        share_syn = (df[measure] / bg_syn).fillna(0)
        share_cen = (df[census] / bg_cen).fillna(0)
        share_area = (df["aland"] / bg_area).fillna(0)
        h = df.index.isin(holdout)
        out.append({
            "measure": measure, "held-out blocks": int(h.sum()),
            "correlation (model)": float(np.corrcoef(share_syn[h], share_cen[h])[0, 1]),
            "correlation (land-area baseline)": float(np.corrcoef(share_area[h], share_cen[h])[0, 1]),
            "mean abs error, pct points (model)": float((share_syn[h] - share_cen[h]).abs().mean() * 100),
            "mean abs error, pct points (baseline)": float((share_area[h] - share_cen[h]).abs().mean() * 100),
        })
    return pd.DataFrame(out)


def _uncertainty_section(stats):
    """Count confidence (households) next to composition confidence (people 65+)."""
    s = stats[stats["source"] == "synthetic"]
    cv = lambda d: (d["se"] / d["estimate"].where(d["estimate"] > 0)).median()
    rows = []
    for level in ["parcel", "block", "block_group", "tract", "city"]:
        at = s[s["level"] == level]
        hh = at[at["variable"] == "households"]
        pop = at[at["variable"] == "population"]
        old = at[(at["variable"] == "age65_plus") & (at["category"] == "yes")]
        grade = hh["confidence"].value_counts(normalize=True)
        rows.append({
            "level": level, "areas": len(hh),
            "median CV, households": float(cv(hh)), "median CV, people": float(cv(pop)),
            "median CV, people 65+": float(cv(old)),
            "households high": f"{grade.get('high', 0):.0%}", "medium": f"{grade.get('medium', 0):.0%}",
            "low": f"{grade.get('low', 0):.0%}",
        })
    return pd.DataFrame(rows)


def validate(stats: pd.DataFrame, validation_stats: pd.DataFrame, pub: pd.DataFrame, blocks: pd.DataFrame,
             holdout: frozenset[str], diagnostics: dict) -> Report:
    r = Report()
    fit, fit_detail = _fit_section(stats, pub, ["block_group", "tract", "city"])
    r.tables["fit_by_area"] = fit_detail
    r.tables["fit_summary"] = fit
    bg = fit_detail[fit_detail["level"] == "block_group"]
    city = fit_detail[fit_detail["level"] == "city"]

    blocks_t = _block_section(validation_stats, blocks, holdout)
    r.tables["held_out_blocks"] = blocks_t
    unc = _uncertainty_section(stats)
    r.tables["uncertainty"] = unc

    def city_val(source, variable, category="total"):
        df = stats if source == "synthetic" else pub
        row = df[(df["level"] == "city") & (df["source"] == source) & (df["variable"] == variable) & (df["category"] == category)]
        return (float(row["estimate"].iloc[0]), float(row["se"].iloc[0])) if len(row) else (np.nan, np.nan)

    for label, var, cat in (("people", "population", "total"), ("households", "households", "total"),
                            ("people 65+", "age65_plus", "yes")):
        s_e, s_se = city_val("synthetic", var, cat)
        p_e, p_se = city_val("published", var, cat)
        r.headline[f"City {label}"] = (f"{s_e:,.0f} ± {MOE_Z * s_se:,.0f} synthetic vs {p_e:,.0f} ± {MOE_Z * p_se:,.0f} ACS "
                                       f"(90% margins; difference {100 * (s_e / p_e - 1):+.1f}%)")
    r.headline["Block-group cells inside the ACS 90% margin"] = f"{(bg['rae'] <= 1).mean():.1%} of {len(bg):,}"
    if len(blocks_t):
        pop = blocks_t[blocks_t["measure"] == "population"].iloc[0]
        r.headline["Held-out blocks, population share"] = (
            f"correlation {pop['correlation (model)']:.2f} with 2020 Census "
            f"(land-area baseline {pop['correlation (land-area baseline)']:.2f}) across {pop['held-out blocks']} blocks")

    r.sections.append(("1. Fit to published ACS, by level", (
        "Synthetic counts from the main run, summed up from parcels, against ACS 2020–2024 published estimates. "
        "RAE (relative allocation error, as in UrbanPop) is |synthetic − published| / published 90% MOE, "
        "so RAE ≤ 1 means the synthetic value is inside the published margin. Block groups are what the model "
        "fits to. Tracts and the city are independent ACS estimates, so they test whether block-group fits add "
        "up correctly. Tracts that extend beyond the study area are left out. Two expected gaps: housing units are "
        "2020 Census block counts while ACS covers 2020–2024, and the study area is the 61 block groups at least "
        "half inside the city, which hold 93 fewer people than the city's own ACS total.\n\n"
        + _md(fit.assign(**{"median RAE": fit["median RAE"].map("{:.2f}".format)}), "{:,.0f}"))))

    snap = city[city["variable"].isin(["age_group", "race_eth", "education", "tenure", "structure", "household_size", "age65_plus"])]
    snap = snap.assign(**{"synthetic ± 90%": snap.apply(lambda x: f"{x['estimate_syn']:,.0f} ± {MOE_Z * x['se_syn']:,.0f}", axis=1),
                          "ACS ± 90%": snap.apply(lambda x: f"{x['estimate_pub']:,.0f} ± {MOE_Z * x['se_pub']:,.0f}", axis=1),
                          "inside ACS margin": np.where(snap["rae"] <= 1, "yes", "no")})
    r.sections.append(("2. City snapshot", _md(snap[["variable", "category", "synthetic ± 90%", "ACS ± 90%", "inside ACS margin"]])))

    r.sections.append(("3. Held-out blocks", (
        "The validation run hides 2020 Census counts for a random 20% of blocks with housing. For those blocks, "
        "placement relies on E911 address units alone. The table compares each held-out block's share of its "
        "block group's people and homes with the 2020 Census. The baseline splits each block group by land area. "
        "Shares are used because the synthetic population reflects 2020–2024, not April 2020.\n\n"
        + _md(blocks_t))))

    r.sections.append(("4. Uncertainty", (
        "Every estimate is the average of 21 placements of the main run, so a parcel shows its expected count "
        "(for example 0.94 households), not one random draw. Its standard error combines two sources. Survey "
        "uncertainty comes from 80 replicate runs (successive-difference formula): each uses one PUMS replicate "
        "weight set and shifts ACS targets within their margins, and they share the main run's placement random "
        "numbers. Placement uncertainty is the spread across the 21 placements. Confidence grades a value by its "
        "coefficient of variation: high ≤ 12%, medium ≤ 40%, low above. The grades below are for household counts "
        "(count confidence). The people 65+ column shows how much less certain composition is at small levels.\n\n"
        + _md(unc))))

    d = diagnostics
    r.sections.append(("5. Fit and placement diagnostics", "\n".join([
        f"- Block-group fits converged: {d['converged']:.0%}; median iterations {d['iterations']:.0f}.",
        f"- Households placed on a parcel of their own structure type: {d['exact']:.1%}; nearest type: "
        f"{d['nearest']:.1%}; beyond parcel unit counts (flagged): {d['overflow']:.1%}.",
        f"- Parcels with housing units: {d['parcels_with_units']:,}; given units only by fallback: {d['fallback']:,}.",
        f"- Group-quarters residents: {d['gq_synthetic']:,.0f} synthetic vs {d['gq_published']:,.0f} ACS. The ACS "
        "figure is total population minus household population, so it carries the error of both.",
    ])))

    r.sections.append(("6. Known limits", "\n".join([
        "- Below the block, nothing can be checked against published data. Parcel values are placements, graded by "
        "their replicate spread, which is wide for small parcels by design.",
        "- Unit counts come from E911 address points, not assessor records. Parcels without a usable address "
        "point get no housing unless their block has no other option.",
        "- Seed households come from one PUMA (Portland, South Portland, Westbrook). Household types that are rare "
        "there are rare in every block group.",
    ])))
    return r
